type Values = Record<string, boolean | number | string | string[]>;

interface SettingsResponse {
  values: Values;
  defaults: Values;
  overridden: string[];
  /** For write-only settings (passwords): whether one is stored. */
  secrets_set?: Record<string, boolean>;
}

interface Field {
  key: string;
  label: string;
  help: string;
  /** `decimal` allows a fraction; `text` is one line; `secret` is write-only; `select` is one of `options`. */
  kind: 'bool' | 'number' | 'decimal' | 'megabytes' | 'list' | 'text' | 'secret' | 'select';
  options?: { value: string; label: string }[];
  min?: number;
  max?: number;
  /** For text: whether it may be left empty, and what it must look like. */
  optional?: boolean;
  pattern?: RegExp;
  patternHint?: string;
  maxLength?: number;
  /** For lists: what each item is (default: a DNS zone). */
  items?: 'zone' | 'country' | 'asn' | 'address';
  /** Shown only while these switches are on. */
  dependsOn?: string[];
  /** Shown only for these values of the first `dependsOn` setting. */
  dependsOnValues?: string[];
}

interface Group {
  title: string;
  description?: string;
  fields: Field[];
  /** A remark depending on the current values (for example a setting that is incomplete). */
  note?: (values: Values) => string | null;
}

